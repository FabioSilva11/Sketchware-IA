package pro.sketchware.supabase

/**
 * Source of the SupabaseClient.java file added to apps that use a Supabase component. It talks to the documented
 * HTTP APIs (PostgREST, Auth, Storage) with OkHttp and Gson, which Sketchware already ships, so the app needs no
 * other library. Compiled and run against a stand-in server in SupabaseClientSourceTest.
 */
object SupabaseClientSource {

    @JvmStatic
    fun generate(packageName: String, url: String, anonKey: String): String = TEMPLATE
        .replace("__PACKAGE__", packageName)
        .replace("__SUPABASE_URL__", javaString(url.trim()))
        .replace("__SUPABASE_ANON_KEY__", javaString(anonKey.trim()))

    /** The text between the quotes of a Java string literal. */
    @JvmStatic
    fun javaString(value: String): String = buildString {
        for (c in value) {
            when (c) {
                '\\' -> append("\\\\")
                '"' -> append("\\\"")
                '\n' -> append("\\n")
                '\r' -> append("\\r")
                else -> append(c)
            }
        }
    }

    private const val TEMPLATE = """package __PACKAGE__;

import android.content.Context;
import android.content.SharedPreferences;
import android.os.Handler;
import android.os.Looper;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.google.gson.JsonPrimitive;
import com.google.gson.JsonSerializer;

import java.io.File;
import java.io.FileOutputStream;
import java.io.InputStream;
import java.io.OutputStream;
import java.net.URLConnection;
import java.net.URLEncoder;
import java.util.HashMap;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;

import okhttp3.MediaType;
import okhttp3.OkHttpClient;
import okhttp3.Request;
import okhttp3.RequestBody;
import okhttp3.Response;
import okhttp3.ResponseBody;

/**
 * Supabase client generated by Sketchware IA: tables (PostgREST), users (Auth) and files (Storage), over HTTP.
 * Results arrive on the main thread. The signed-in user's session is kept in SharedPreferences and used by
 * every request, so row level security policies see the user.
 */
public class SupabaseClient {

    public static final String URL = "__SUPABASE_URL__";
    public static final String ANON_KEY = "__SUPABASE_ANON_KEY__";

    private static final MediaType JSON = MediaType.parse("application/json; charset=utf-8");
    private static final ExecutorService EXECUTOR = Executors.newCachedThreadPool();
    private static final Handler MAIN = new Handler(Looper.getMainLooper());
    // Numbers of the blocks are doubles: 1.0 is sent as 1 so it fits integer columns.
    private static final Gson GSON = new GsonBuilder().serializeNulls()
            .registerTypeAdapter(Double.class, (JsonSerializer<Double>) (value, type, context) ->
                    value == Math.rint(value) && !Double.isInfinite(value) && Math.abs(value) < 1e15
                            ? new JsonPrimitive(value.longValue()) : new JsonPrimitive(value))
            .create();
    private static final Object REFRESH_LOCK = new Object();
    private static OkHttpClient client;

    public interface DatabaseListener {
        void onResponse(String tag, String response);

        void onError(String tag, String message);
    }

    public interface AuthListener {
        void onSuccess(String action, String userId, String email);

        void onError(String action, String message);
    }

    public interface StorageListener {
        void onSuccess(String action, String path, String result);

        void onError(String action, String message);
    }

    private static synchronized OkHttpClient client() {
        if (client == null) {
            client = new OkHttpClient.Builder()
                    .connectTimeout(20, TimeUnit.SECONDS)
                    .readTimeout(60, TimeUnit.SECONDS)
                    .writeTimeout(60, TimeUnit.SECONDS)
                    .build();
        }
        return client;
    }

    private static String baseUrl() {
        String url = URL.trim();
        while (url.endsWith("/")) url = url.substring(0, url.length() - 1);
        return url;
    }

    private static String encodePath(String path) {
        StringBuilder encoded = new StringBuilder();
        for (String segment : path.split("/")) {
            if (segment.isEmpty()) continue;
            if (encoded.length() > 0) encoded.append('/');
            try {
                encoded.append(URLEncoder.encode(segment, "UTF-8").replace("+", "%20"));
            } catch (Exception e) {
                encoded.append(segment);
            }
        }
        return encoded.toString();
    }

    private static String text(JsonObject object, String key) {
        JsonElement value = object == null ? null : object.get(key);
        return value == null || value.isJsonNull() || !value.isJsonPrimitive() ? "" : value.getAsString();
    }

    private static String message(Exception e) {
        return e.getMessage() == null ? e.toString() : e.getMessage();
    }

    /** The message Supabase sends with an error: PostgREST, Auth and Storage each name it differently. */
    private static String errorMessage(int code, String body) {
        try {
            JsonObject error = JsonParser.parseString(body).getAsJsonObject();
            for (String key : new String[]{"message", "msg", "error_description", "error"}) {
                String value = text(error, key);
                if (!value.isEmpty()) return value;
            }
        } catch (Exception ignored) {
        }
        return body.isEmpty() ? "HTTP " + code : body;
    }

    private static RequestBody json(Object value) {
        return RequestBody.create(GSON.toJson(value), JSON);
    }

    // ---- Session ----

    private static SharedPreferences prefs(Context context) {
        return context.getSharedPreferences("supabase_session", Context.MODE_PRIVATE);
    }

    private static void saveSession(Context context, JsonObject session) {
        JsonObject user = session.has("user") && session.get("user").isJsonObject() ? session.getAsJsonObject("user") : null;
        long expiresIn = session.has("expires_in") ? session.get("expires_in").getAsLong() : 3600;
        long expiresAt = session.has("expires_at") ? session.get("expires_at").getAsLong()
                : System.currentTimeMillis() / 1000 + expiresIn;
        prefs(context).edit()
                .putString("access_token", text(session, "access_token"))
                .putString("refresh_token", text(session, "refresh_token"))
                .putLong("expires_at", expiresAt)
                .putString("user_id", text(user, "id"))
                .putString("email", text(user, "email"))
                .apply();
    }

    private static void clearSession(Context context) {
        prefs(context).edit().clear().apply();
    }

    /**
     * The user's token, renewed when it is about to expire; the anon key when nobody is signed in. One renewal at a
     * time: a refresh token works once, so requests made together must not each try to use it.
     */
    private static String bearer(Context context) throws Exception {
        synchronized (REFRESH_LOCK) {
            SharedPreferences prefs = prefs(context);
            String access = prefs.getString("access_token", "");
            if (access.isEmpty()) return ANON_KEY;
            String refresh = prefs.getString("refresh_token", "");
            if (refresh.isEmpty() || System.currentTimeMillis() / 1000 < prefs.getLong("expires_at", 0) - 60) {
                return access;
            }
            JsonObject body = new JsonObject();
            body.addProperty("refresh_token", refresh);
            Request request = new Request.Builder()
                    .url(baseUrl() + "/auth/v1/token?grant_type=refresh_token")
                    .header("apikey", ANON_KEY)
                    .header("Authorization", "Bearer " + ANON_KEY)
                    .post(RequestBody.create(body.toString(), JSON))
                    .build();
            try (Response response = client().newCall(request).execute()) {
                String text = readBody(response);
                if (response.isSuccessful()) {
                    saveSession(context, JsonParser.parseString(text).getAsJsonObject());
                    return prefs(context).getString("access_token", ANON_KEY);
                }
                if (response.code() == 400) {
                    // The refresh token was revoked or already used: signed out for good, continue as a visitor.
                    clearSession(context);
                    return ANON_KEY;
                }
                throw new Exception(errorMessage(response.code(), text));
            }
        }
    }

    private static String readBody(Response response) throws Exception {
        ResponseBody body = response.body();
        return body == null ? "" : body.string();
    }

    /** Sends a request with the project key and the user's token (or the anon key), off the main thread. */
    private static String send(Context context, Request.Builder builder, boolean asUser) throws Exception {
        builder.header("apikey", ANON_KEY)
                .header("Authorization", "Bearer " + (asUser ? bearer(context) : ANON_KEY));
        try (Response response = client().newCall(builder.build()).execute()) {
            String text = readBody(response);
            if (!response.isSuccessful()) throw new Exception(errorMessage(response.code(), text));
            return text;
        }
    }

    // ---- Database ----

    /** One table, through PostgREST: https://supabase.com/docs/guides/api */
    public static class Database {
        private final Context context;
        private final String table;

        public Database(Context context, String table) {
            this.context = context.getApplicationContext();
            this.table = table.trim();
        }

        private String url(String query) {
            String url = baseUrl() + "/rest/v1/" + encodePath(table);
            String trimmed = query == null ? "" : query.trim();
            if (trimmed.startsWith("?")) trimmed = trimmed.substring(1);
            return trimmed.isEmpty() ? url : url + "?" + trimmed;
        }

        /** {@code query} in PostgREST syntax, e.g. {@code select=*&done=eq.false&order=id.desc}. */
        public void select(String query, String tag, DatabaseListener listener) {
            String filter = query == null || query.trim().isEmpty() ? "select=*" : query;
            run(new Request.Builder().url(url(filter)).get(), tag, listener);
        }

        public void insert(HashMap<String, Object> row, String tag, DatabaseListener listener) {
            run(new Request.Builder().url(url("")).header("Prefer", "return=representation").post(json(row)), tag, listener);
        }

        /** Inserts the row, or updates the one with the same primary key. */
        public void upsert(HashMap<String, Object> row, String tag, DatabaseListener listener) {
            run(new Request.Builder().url(url(""))
                    .header("Prefer", "resolution=merge-duplicates,return=representation").post(json(row)), tag, listener);
        }

        /** {@code filter} picks the rows, e.g. {@code id=eq.1}; an empty one is refused rather than changing every row. */
        public void update(String filter, HashMap<String, Object> values, String tag, DatabaseListener listener) {
            if (refuseEmpty(filter, tag, listener)) return;
            run(new Request.Builder().url(url(filter)).header("Prefer", "return=representation").patch(json(values)), tag, listener);
        }

        public void delete(String filter, String tag, DatabaseListener listener) {
            if (refuseEmpty(filter, tag, listener)) return;
            run(new Request.Builder().url(url(filter)).header("Prefer", "return=representation").delete(), tag, listener);
        }

        private boolean refuseEmpty(String filter, String tag, DatabaseListener listener) {
            if (filter != null && !filter.trim().isEmpty()) return false;
            MAIN.post(() -> {
                if (listener != null) listener.onError(tag, "A filter is required, e.g. id=eq.1");
            });
            return true;
        }

        private void run(Request.Builder request, String tag, DatabaseListener listener) {
            EXECUTOR.execute(() -> {
                try {
                    String body = send(context, request, true);
                    MAIN.post(() -> {
                        if (listener != null) listener.onResponse(tag, body);
                    });
                } catch (Exception e) {
                    String error = message(e);
                    MAIN.post(() -> {
                        if (listener != null) listener.onError(tag, error);
                    });
                }
            });
        }
    }

    // ---- Auth ----

    /** Users with email and password: https://supabase.com/docs/guides/auth */
    public static class Auth {
        private final Context context;

        public Auth(Context context) {
            this.context = context.getApplicationContext();
        }

        public void signUp(String email, String password, AuthListener listener) {
            JsonObject body = new JsonObject();
            body.addProperty("email", email);
            body.addProperty("password", password);
            run("signUp", new Request.Builder().url(baseUrl() + "/auth/v1/signup")
                    .post(RequestBody.create(body.toString(), JSON)), email, listener);
        }

        public void signIn(String email, String password, AuthListener listener) {
            JsonObject body = new JsonObject();
            body.addProperty("email", email);
            body.addProperty("password", password);
            run("signIn", new Request.Builder().url(baseUrl() + "/auth/v1/token?grant_type=password")
                    .post(RequestBody.create(body.toString(), JSON)), email, listener);
        }

        public void resetPassword(String email, AuthListener listener) {
            JsonObject body = new JsonObject();
            body.addProperty("email", email);
            run("resetPassword", new Request.Builder().url(baseUrl() + "/auth/v1/recover")
                    .post(RequestBody.create(body.toString(), JSON)), email, listener);
        }

        public void signOut(AuthListener listener) {
            String userId = getUserId();
            String email = getEmail();
            String token = getAccessToken();
            EXECUTOR.execute(() -> {
                if (!token.isEmpty()) {
                    try {
                        Request.Builder request = new Request.Builder().url(baseUrl() + "/auth/v1/logout")
                                .post(RequestBody.create("{}", JSON));
                        send(context, request, true);
                    } catch (Exception ignored) {
                        // Signed out on this device even when the server can't be reached.
                    }
                }
                clearSession(context);
                MAIN.post(() -> {
                    if (listener != null) listener.onSuccess("signOut", userId, email);
                });
            });
        }

        public boolean isSignedIn() {
            return !getAccessToken().isEmpty();
        }

        public String getUserId() {
            return prefs(context).getString("user_id", "");
        }

        public String getEmail() {
            return prefs(context).getString("email", "");
        }

        public String getAccessToken() {
            return prefs(context).getString("access_token", "");
        }

        private void run(String action, Request.Builder request, String requestedEmail, AuthListener listener) {
            EXECUTOR.execute(() -> {
                try {
                    String text = send(context, request, false);
                    JsonElement parsed = text.trim().isEmpty() ? new JsonObject() : JsonParser.parseString(text);
                    JsonObject result = parsed.isJsonObject() ? parsed.getAsJsonObject() : new JsonObject();
                    JsonObject user = result;
                    if (result.has("access_token")) {
                        saveSession(context, result);
                        user = result.has("user") && result.get("user").isJsonObject() ? result.getAsJsonObject("user") : null;
                    }
                    String userId = text(user, "id");
                    String email = text(user, "email").isEmpty() ? requestedEmail : text(user, "email");
                    MAIN.post(() -> {
                        if (listener != null) listener.onSuccess(action, userId, email);
                    });
                } catch (Exception e) {
                    String error = message(e);
                    MAIN.post(() -> {
                        if (listener != null) listener.onError(action, error);
                    });
                }
            });
        }
    }

    // ---- Storage ----

    /** Files of one bucket: https://supabase.com/docs/guides/storage */
    public static class Storage {
        private final Context context;
        private final String bucket;

        public Storage(Context context, String bucket) {
            this.context = context.getApplicationContext();
            this.bucket = bucket.trim();
        }

        private String objectUrl(String path) {
            return baseUrl() + "/storage/v1/object/" + encodePath(bucket) + "/" + encodePath(path);
        }

        /** Where a file of a public bucket can be opened, e.g. by an image loader. */
        public String getPublicUrl(String path) {
            return baseUrl() + "/storage/v1/object/public/" + encodePath(bucket) + "/" + encodePath(path);
        }

        /** Uploads a local file, replacing the one at {@code path}; the result is its public URL. */
        public void upload(String localPath, String path, StorageListener listener) {
            EXECUTOR.execute(() -> {
                try {
                    File file = new File(localPath);
                    if (!file.isFile()) throw new Exception("File not found: " + localPath);
                    String type = URLConnection.guessContentTypeFromName(file.getName());
                    MediaType mediaType = MediaType.parse(type == null ? "application/octet-stream" : type);
                    send(context, new Request.Builder().url(objectUrl(path)).header("x-upsert", "true")
                            .post(RequestBody.create(file, mediaType)), true);
                    deliver(listener, "upload", path, getPublicUrl(path), null);
                } catch (Exception e) {
                    deliver(listener, "upload", path, "", message(e));
                }
            });
        }

        /** Downloads {@code path} into a local file; the result is that file's path. */
        public void download(String path, String localPath, StorageListener listener) {
            EXECUTOR.execute(() -> {
                Request.Builder builder = new Request.Builder().url(objectUrl(path)).get();
                try {
                    builder.header("apikey", ANON_KEY).header("Authorization", "Bearer " + bearer(context));
                    try (Response response = client().newCall(builder.build()).execute()) {
                        if (!response.isSuccessful()) throw new Exception(errorMessage(response.code(), readBody(response)));
                        File file = new File(localPath);
                        File parent = file.getParentFile();
                        if (parent != null && !parent.exists() && !parent.mkdirs()) {
                            throw new Exception("Can't create " + parent);
                        }
                        ResponseBody body = response.body();
                        if (body == null) throw new Exception("Empty response");
                        try (InputStream in = body.byteStream(); OutputStream out = new FileOutputStream(file)) {
                            byte[] buffer = new byte[8192];
                            int read;
                            while ((read = in.read(buffer)) != -1) out.write(buffer, 0, read);
                        }
                    }
                    deliver(listener, "download", path, localPath, null);
                } catch (Exception e) {
                    deliver(listener, "download", path, "", message(e));
                }
            });
        }

        public void delete(String path, StorageListener listener) {
            EXECUTOR.execute(() -> {
                try {
                    JsonObject body = new JsonObject();
                    JsonArray prefixes = new JsonArray();
                    prefixes.add(path);
                    body.add("prefixes", prefixes);
                    String text = send(context, new Request.Builder()
                            .url(baseUrl() + "/storage/v1/object/" + encodePath(bucket))
                            .delete(RequestBody.create(body.toString(), JSON)), true);
                    // Storage answers 200 with an empty list when nothing matched the path.
                    JsonElement deleted = text.trim().isEmpty() ? new JsonArray() : JsonParser.parseString(text);
                    if (deleted.isJsonArray() && deleted.getAsJsonArray().size() == 0) {
                        throw new Exception("Object not found: " + path);
                    }
                    deliver(listener, "delete", path, "", null);
                } catch (Exception e) {
                    deliver(listener, "delete", path, "", message(e));
                }
            });
        }

        private void deliver(StorageListener listener, String action, String path, String result, String error) {
            MAIN.post(() -> {
                if (listener == null) return;
                if (error == null) listener.onSuccess(action, path, result);
                else listener.onError(action, error);
            });
        }
    }
