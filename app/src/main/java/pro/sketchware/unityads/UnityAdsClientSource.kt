    /** A 320x50 banner, from a placement such as Banner_Android, shown inside a layout of the screen. */
    public static class Banner {
        private final String placementId;
        private BannerAd ad;
        private boolean loading;

        public Banner(String placementId) {
            this.placementId = placementId;
        }

        public boolean isLoaded() {
            return ad != null;
        }

        /** Loads a banner and puts it in the layout, in place of the one this component showed before. */
        public void load(View layout, final BannerListener listener) {
            if (!(layout instanceof ViewGroup)) {
                listener.onFailedToLoad(ERROR_NOT_READY, "Show the banner in a layout, such as a LinearLayout");
                return;
            }
            if (loading) return;
            loading = true;
            final ViewGroup container = (ViewGroup) layout;
            whenStarted(new Started() {
                @Override
                public void run(UnityAdsError error) {
                    if (error != null) {
                        loading = false;
                        listener.onFailedToLoad(code(error), message(error));
                        return;
                    }
                    BannerShowListener showListener = new BannerShowListener() {
                        @Override
                        public void onImpression(BannerAd bannerAd) {
                            onMain(new Runnable() {
                                @Override
                                public void run() {
                                    listener.onShown();
                                }
                            });
                        }

                        @Override
                        public void onClicked(BannerAd bannerAd) {
                            onMain(new Runnable() {
                                @Override
                                public void run() {
                                    listener.onClicked();
                                }
                            });
                        }

                        @Override
                        public void onFailedToShow(BannerAd bannerAd, final UnityAdsError showError) {
                            onMain(new Runnable() {
                                @Override
                                public void run() {
                                    listener.onShowFailed(code(showError), message(showError));
                                }
                            });
                        }
                    };
                    BannerConfiguration configuration = new BannerConfiguration.Builder(placementId,
                            new BannerSize(320, 50), showListener).build();
                    BannerAd.load(configuration, new LoadListener<BannerAd>() {
                        @Override
                        public void onAdLoaded(final BannerAd loaded, final UnityAdsError loadError) {
                            onMain(new Runnable() {
                                @Override
                                public void run() {
                                    loading = false;
                                    View view = loaded == null ? null : loaded.getView();
                                    if (view == null) {
                                        listener.onFailedToLoad(code(loadError), message(loadError));
                                        return;
                                    }
                                    remove();
                                    ad = loaded;
                                    if (view.getParent() instanceof ViewGroup) {
                                        ((ViewGroup) view.getParent()).removeView(view);
                                    }
                                    container.addView(view, new ViewGroup.LayoutParams(
                                            ViewGroup.LayoutParams.WRAP_CONTENT, ViewGroup.LayoutParams.WRAP_CONTENT));
                                    listener.onLoaded();
                                }
                            });
                        }
                    });
                }
            });
        }

        /** Takes the banner off the screen. */
        public void remove() {
            if (ad == null) return;
            View view = ad.getView();
            if (view != null && view.getParent() instanceof ViewGroup) {
                ((ViewGroup) view.getParent()).removeView(view);
            }
            ad = null;
        }
    }
}
