package pro.sketchware.unityads

import pro.sketchware.supabase.SupabaseClientSource

/**
 * Source of the UnityAdsClient.java file added to apps that use a Unity Ads component. It uses the SDK's current
 * API (InitializationConfiguration, InterstitialAd, RewardedAd, BannerAd), which replaced UnityAds.load/show and
 * the IUnityAds* listeners in 4.19: those are deprecated and go away in 5.0.
 *
 * The SDK is started once, with the project's game ID, by the first load: privacy choices set before it (the
 * consent blocks) are sent with the first request. Loads asked for while it starts wait for it. Every callback
 * reaches the component's listener on the main thread.
 */
object UnityAdsClientSource {

    @JvmStatic
    fun generate(packageName: String, gameId: String, testMode: Boolean): String = TEMPLATE
        .replace("__PACKAGE__", packageName)
        .replace("__GAME_ID__", SupabaseClientSource.javaString(gameId.trim()))
        .replace("__TEST_MODE__", testMode.toString())

    /** UnityBannerView.java: the Unity Banner widget of the layout editor, a FrameLayout the banner is shown in. */
    @JvmStatic
    fun generateBannerView(packageName: String): String = BANNER_VIEW_TEMPLATE.replace("__PACKAGE__", packageName)

    /** The class the layouts name for a Unity Banner widget. */
    @JvmStatic
    fun bannerViewClass(packageName: String): String =
        if (packageName.isEmpty()) "UnityBannerView" else "$packageName.UnityBannerView"

    private const val BANNER_VIEW_TEMPLATE = """package __PACKAGE__;

import android.content.Context;
import android.util.AttributeSet;
import android.widget.FrameLayout;

/**
 * The Unity Banner widget, generated by Sketchware IA. Its placement ID comes from the layout (android:tag, set
 * from the widget's properties); the banner is loaded into this view and replaces the one shown before.
 */
public class UnityBannerView extends FrameLayout {

    private static final UnityAdsClient.BannerListener NO_LISTENER = new UnityAdsClient.BannerListener() {
        @Override
        public void onLoaded() {
        }

        @Override
        public void onFailedToLoad(int code, String message) {
        }

        @Override
        public void onShown() {
        }

        @Override
        public void onClicked() {
        }

        @Override
        public void onShowFailed(int code, String message) {
        }
    };

    private UnityAdsClient.Banner banner;
    private UnityAdsClient.BannerListener listener = NO_LISTENER;

    public UnityBannerView(Context context) {
        this(context, null);
    }

    public UnityBannerView(Context context, AttributeSet attrs) {
        super(context, attrs);
        Object tag = getTag();
        banner = new UnityAdsClient.Banner(tag == null ? "" : tag.toString().trim());
    }

    public String getPlacementId() {
        Object tag = getTag();
        return tag == null ? "" : tag.toString();
    }

    /** Uses another placement from the next load on. */
    public void setPlacementId(String placementId) {
        banner.remove();
        setTag(placementId);
        banner = new UnityAdsClient.Banner(placementId == null ? "" : placementId.trim());
    }

    public void setListener(UnityAdsClient.BannerListener listener) {
        this.listener = listener == null ? NO_LISTENER : listener;
    }

    public void load() {
        banner.load(this, listener);
    }

    public void remove() {
        banner.remove();
    }

    public boolean isLoaded() {
        return banner.isLoaded();
    }
}
"""

    private const val TEMPLATE = """package __PACKAGE__;

import android.app.Activity;
import android.os.Handler;
import android.os.Looper;
import android.view.View;
import android.view.ViewGroup;

import com.unity3d.ads.AdExpiredListener;
import com.unity3d.ads.BannerAd;
import com.unity3d.ads.BannerConfiguration;
import com.unity3d.ads.BannerShowListener;
import com.unity3d.ads.BannerSize;
import com.unity3d.ads.InitializationConfiguration;
import com.unity3d.ads.InitializationListener;
import com.unity3d.ads.InterstitialAd;
import com.unity3d.ads.InterstitialShowListener;
import com.unity3d.ads.LoadConfiguration;
import com.unity3d.ads.LoadListener;
import com.unity3d.ads.RewardedAd;
import com.unity3d.ads.RewardedShowListener;
import com.unity3d.ads.ShowConfiguration;
import com.unity3d.ads.ShowFinishState;
import com.unity3d.ads.UnityAds;
import com.unity3d.ads.UnityAdsError;

import java.util.ArrayList;

/**
 * Unity Ads, generated by Sketchware IA on the SDK's current API. The SDK starts with the first load, using the
 * game ID set in the project's Library screen; loads asked for while it starts wait for it. An ad is shown once:
 * load the next one after it closes. Callbacks arrive on the main thread.
 */
public class UnityAdsClient {

    public static final String GAME_ID = "__GAME_ID__";
    /** Test ads only: on for the builds Sketchware runs, and for exported ones when chosen in the Library screen. */
    public static final boolean TEST_MODE = __TEST_MODE__;
    /** Code of the errors this class reports itself, e.g. showing an ad before it has loaded. */
    public static final int ERROR_NOT_READY = -1;

    private static final Handler MAIN = new Handler(Looper.getMainLooper());
    private static final ArrayList<Started> WAITING = new ArrayList<>();
    private static boolean starting;

    public interface InterstitialListener {
        void onLoaded();

        void onFailedToLoad(int code, String message);

        void onShowStarted();

        void onClicked();

        void onShowCompleted(boolean skipped);

        void onShowFailed(int code, String message);

        void onExpired();
    }

    public interface RewardedListener extends InterstitialListener {
        void onRewarded();
    }

    public interface BannerListener {
        void onLoaded();

        void onFailedToLoad(int code, String message);

        void onShown();

        void onClicked();

        void onShowFailed(int code, String message);
    }

    /** Run once the SDK has started (error null), or couldn't start. */
    private interface Started {
        void run(UnityAdsError error);
    }

    private static void onMain(Runnable runnable) {
        if (Looper.myLooper() == Looper.getMainLooper()) {
            runnable.run();
        } else {
            MAIN.post(runnable);
        }
    }

    private static int code(UnityAdsError error) {
        return error == null ? ERROR_NOT_READY : error.getCode();
    }

    private static String message(UnityAdsError error) {
        return error == null || error.getMessage() == null ? "Unknown Unity Ads error" : error.getMessage();
    }

    private static void whenStarted(Started started) {
        if (UnityAds.isInitialized()) {
            started.run(null);
            return;
        }
        WAITING.add(started);
        if (starting) return;
        if (GAME_ID.trim().isEmpty()) {
            finishStart(new UnityAdsError(ERROR_NOT_READY, "No Unity Ads game ID: set it in the Library screen of Sketchware"));
            return;
        }
        starting = true;
        InitializationConfiguration configuration = new InitializationConfiguration.Builder(GAME_ID.trim())
                .withTestMode(TEST_MODE)
                .build();
        UnityAds.initialize(configuration, new InitializationListener() {
            @Override
            public void onInitializationComplete(final UnityAdsError error) {
                onMain(new Runnable() {
                    @Override
                    public void run() {
                        starting = false;
                        finishStart(error);
                    }
                });
            }
        });
    }

    private static void finishStart(UnityAdsError error) {
        ArrayList<Started> waiting = new ArrayList<>(WAITING);
        WAITING.clear();
        if (error != null) {
            // Failed starts are tried again by the next load, e.g. once the device is back online.
            error = new UnityAdsError(error.getCode(), "Unity Ads couldn't start: " + message(error));
        }
        for (Started started : waiting) {
            started.run(error);
        }
    }

    /** Whether the SDK has started: it does with the first load. */
    public static boolean isInitialized() {
        return UnityAds.isInitialized();
    }

    /** A fullscreen ad that can be closed, from a placement such as Interstitial_Android. */
    public static class Interstitial {
        private final Activity activity;
        private final String placementId;
        private InterstitialAd ad;
        private boolean loading;

        public Interstitial(Activity activity, String placementId) {
            this.activity = activity;
            this.placementId = placementId;
        }

        public boolean isLoaded() {
            return ad != null;
        }

        public void load(final InterstitialListener listener) {
            if (loading) return;
            if (ad != null) {
                listener.onLoaded();
                return;
            }
            loading = true;
            whenStarted(new Started() {
                @Override
                public void run(UnityAdsError error) {
                    if (error != null) {
                        loading = false;
                        listener.onFailedToLoad(code(error), message(error));
                        return;
                    }
                    InterstitialAd.load(new LoadConfiguration.Builder(placementId).build(), new LoadListener<InterstitialAd>() {
                        @Override
                        public void onAdLoaded(final InterstitialAd loaded, final UnityAdsError loadError) {
                            onMain(new Runnable() {
                                @Override
                                public void run() {
                                    loading = false;
                                    if (loaded == null) {
                                        listener.onFailedToLoad(code(loadError), message(loadError));
                                        return;
                                    }
                                    ad = loaded;
                                    loaded.setOnAdExpired(new AdExpiredListener<InterstitialAd>() {
                                        @Override
                                        public void onAdExpired(InterstitialAd expired) {
                                            onMain(new Runnable() {
                                                @Override
                                                public void run() {
                                                    if (ad != loaded) return;
                                                    ad = null;
                                                    listener.onExpired();
                                                }
                                            });
                                        }
                                    });
                                    listener.onLoaded();
                                }
                            });
                        }
                    });
                }
            });
        }

        public void show(final InterstitialListener listener) {
            InterstitialAd shown = ad;
            if (shown == null) {
                listener.onShowFailed(ERROR_NOT_READY, "The ad isn't loaded yet: load it and show it after it has loaded");
                return;
            }
            ad = null;
            shown.show(activity, new ShowConfiguration.Builder().build(), new InterstitialShowListener() {
                @Override
                public void onStarted(InterstitialAd unityAd) {
                    onMain(new Runnable() {
                        @Override
                        public void run() {
                            listener.onShowStarted();
                        }
                    });
                }

                @Override
                public void onClicked(InterstitialAd unityAd) {
                    onMain(new Runnable() {
                        @Override
                        public void run() {
                            listener.onClicked();
                        }
                    });
                }

                @Override
                public void onCompleted(InterstitialAd unityAd, final ShowFinishState state) {
                    onMain(new Runnable() {
                        @Override
                        public void run() {
                            listener.onShowCompleted(state == ShowFinishState.SKIPPED);
                        }
                    });
                }

                @Override
                public void onFailed(InterstitialAd unityAd, final UnityAdsError error) {
                    onMain(new Runnable() {
                        @Override
                        public void run() {
                            listener.onShowFailed(code(error), message(error));
                        }
                    });
                }
            });
        }
    }

